package ex_16_jun_program;

public class Lab089_Interview {
    public static void main(String[] args) {
        char ch = 'b';
        switch (ch){
            case 65:
                System.out.println("the letter is A");
                break;
            case 66:
                System.out.println("the letter is b");
                break;
            default:
                System.out.println("no match");
        }
    }
}
